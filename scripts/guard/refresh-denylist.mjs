#!/usr/bin/env node
// Builds the private denylist for the leak guard from local data sources and
// writes it to ~/.config/<repo>-guard/denylist.txt (mode 0600), outside the
// repository. Values are never printed.
//
// Sources:
//   Telegrowl/App/Config.swift          Telegram api_id / api_hash
//   Configs/Signing.local.xcconfig      Apple Team ID
//   ~/.claude/channels/telegram/        Telegram user/chat IDs, bot tokens
//   your home directory path
//   ~/.config/<repo>-guard/manual.txt   extra entries you maintain by hand
//                                       (same `kind<TAB>value` format)
//
// Entries whose value already appears in the working tree are skipped (they
// would block every commit) and listed for manual review: a skip can also hide
// an existing leak.

import { execFileSync } from 'node:child_process';
import { chmodSync, existsSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { join, sep } from 'node:path';
import { denyRegex, parseDenylist, redact } from './rules.mjs';

const root = execFileSync('git', ['rev-parse', '--show-toplevel'], { encoding: 'utf8' }).trim();
const name = `${root.split(sep).pop().replace(/-public$/, '')}-guard`;
const dir = join(homedir(), '.config', name);
const out = join(dir, 'denylist.txt');
const manual = join(dir, 'manual.txt');

const entries = new Map(); // value -> { kind, source }
const add = (kind, value, source) => {
  if (value && !entries.has(value)) entries.set(value, { kind, source });
};
const read = (file) => (existsSync(file) && statSync(file).isFile() ? readFileSync(file, 'utf8') : null);

// Telegram API credentials
const config = read(join(root, 'Telegrowl/App/Config.swift'));
if (config) {
  const id = config.match(/telegramApiId\s*:\s*Int\s*=\s*(\d{5,})/)?.[1];
  const hash = config.match(/telegramApiHash\s*=\s*"([0-9a-fA-F]{32})"/)?.[1];
  add('ticker', id, 'Config.swift api_id');
  add('ticker-ci', hash, 'Config.swift api_hash');
}

// Apple Team ID
const signing = read(join(root, 'Configs/Signing.local.xcconfig'));
const team = signing?.match(/^\s*DEVELOPMENT_TEAM\s*=\s*([A-Z0-9]{10})\s*$/m)?.[1];
add('ticker', team, 'Signing.local.xcconfig team');

// Telegram channel plugin: user/chat IDs and bot tokens
const tgDir = join(homedir(), '.claude', 'channels', 'telegram');
if (existsSync(tgDir)) {
  for (const f of readdirSync(tgDir)) {
    if (f.endsWith('.pid')) continue;
    const text = read(join(tgDir, f));
    if (!text || text.length > 1_000_000) continue;
    for (const m of text.matchAll(/\b\d{8,10}:[A-Za-z0-9_-]{35}\b/g)) add('literal', m[0], `telegram plugin ${f} (token)`);
    for (const m of text.matchAll(/(?<![\d:])-?\d{6,15}(?![\d:])/g)) add('ticker', m[0], `telegram plugin ${f} (id)`);
  }
}

// Home directory
add('literal', homedir(), 'home directory');

// Manual entries
const manualText = read(manual);
if (manualText) for (const e of parseDenylist(manualText)) add(e.kind, e.value, 'manual.txt');

// Skip values already present in the working tree, but report them
const tracked = execFileSync('git', ['ls-files', '-z'], { cwd: root, encoding: 'utf8' }).split('\0').filter(Boolean);
const corpus = tracked.map((f) => {
  try { return readFileSync(join(root, f), 'utf8'); } catch { return ''; }
}).join('\n');
const skipped = [];
const lines = [
  `# ${name} denylist — generated by scripts/guard/refresh-denylist.mjs`,
  '# kind<TAB>value  (kinds: ticker, ticker-ci, word-ci, literal, regex)',
];
for (const [value, { kind, source }] of entries) {
  const re = denyRegex(kind, value);
  if (re && re.test(corpus)) {
    skipped.push({ kind, value, source });
    continue;
  }
  lines.push(`${kind}\t${value}\t# ${source}`);
}

mkdirSync(dir, { recursive: true, mode: 0o700 });
writeFileSync(out, `${lines.join('\n')}\n`, { mode: 0o600 });
chmodSync(out, 0o600);

console.log(`Wrote ${lines.length - 2} entries to ${out} (mode 0600).`);
if (skipped.length) {
  console.log(`\nSkipped ${skipped.length} value(s) already in the working tree. Review each: it may be a leak.`);
  for (const s of skipped) console.log(`  ${s.kind.padEnd(10)} ${redact(s.value)}  from ${s.source}`);
}
